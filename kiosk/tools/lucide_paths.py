"""Regenerate kiosk/icons/Icons.mjs from lucide's SVG files.

Qt's Shape draws one SVG path per icon, so every lucide element (rect, circle,
line, ...) is turned into path data here and joined into a single string.
To add an icon: put its lucide name in ICONS and run
    python kiosk/tools/lucide_paths.py
"""
import os
import re
import urllib.request
import xml.etree.ElementTree as ET

# Same release the old web kiosk used, so the glyphs do not change.
LUCIDE_VERSION = "1.52.0"
_SVG_URL = "https://unpkg.com/lucide-static@{version}/icons/{name}.svg"
_OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "icons", "Icons.mjs")

ICONS = [
    "arrow-big-up", "bell", "calendar", "check", "delete", "download", "heart", "lock",
    "mail", "minus", "moon", "music", "pause", "play", "plus", "refresh-cw",
    "rotate-cw", "settings", "shuffle", "skip-back", "skip-forward", "star",
    "trash-2", "triangle-alert", "user-plus", "wifi-off", "x",
]

_HEADER = """\
// Generated by kiosk/tools/lucide_paths.py from lucide-static {version}. Do not edit.
// Lucide is ISC licensed: https://lucide.dev/license
// Every icon is a 24x24 stroke path (width 2, round caps and joins).
"""


def _num(value: str) -> float:
    return float(value) if value else 0.0


def _fmt(value: float) -> str:
    return f"{value:.4f}".rstrip("0").rstrip(".")


def _rect(el: ET.Element) -> str:
    x, y = _num(el.get("x")), _num(el.get("y"))
    w, h = _num(el.get("width")), _num(el.get("height"))
    rx = _num(el.get("rx") or el.get("ry"))
    ry = _num(el.get("ry") or el.get("rx"))
    if not rx and not ry:
        return f"M{_fmt(x)} {_fmt(y)}h{_fmt(w)}v{_fmt(h)}h{_fmt(-w)}z"
    return (
        f"M{_fmt(x + rx)} {_fmt(y)}h{_fmt(w - 2 * rx)}a{_fmt(rx)} {_fmt(ry)} 0 0 1 {_fmt(rx)} {_fmt(ry)}"
        f"v{_fmt(h - 2 * ry)}a{_fmt(rx)} {_fmt(ry)} 0 0 1 {_fmt(-rx)} {_fmt(ry)}"
        f"h{_fmt(-(w - 2 * rx))}a{_fmt(rx)} {_fmt(ry)} 0 0 1 {_fmt(-rx)} {_fmt(-ry)}"
        f"v{_fmt(-(h - 2 * ry))}a{_fmt(rx)} {_fmt(ry)} 0 0 1 {_fmt(rx)} {_fmt(-ry)}z"
    )


def _ellipse(cx: float, cy: float, rx: float, ry: float) -> str:
    return (
        f"M{_fmt(cx - rx)} {_fmt(cy)}a{_fmt(rx)} {_fmt(ry)} 0 1 0 {_fmt(2 * rx)} 0"
        f"a{_fmt(rx)} {_fmt(ry)} 0 1 0 {_fmt(-2 * rx)} 0z"
    )


def _points(el: ET.Element, close: bool) -> str:
    pairs = el.get("points", "").replace(",", " ").split()
    head = f"M{pairs[0]} {pairs[1]}"
    rest = "".join(f"L{pairs[i]} {pairs[i + 1]}" for i in range(2, len(pairs), 2))
    return head + rest + ("z" if close else "")


def element_path(el: ET.Element) -> str:
    tag = el.tag.split("}")[-1]
    if tag == "path":
        return el.get("d", "")
    if tag == "line":
        return f"M{el.get('x1')} {el.get('y1')}L{el.get('x2')} {el.get('y2')}"
    if tag == "polyline":
        return _points(el, close=False)
    if tag == "polygon":
        return _points(el, close=True)
    if tag == "rect":
        return _rect(el)
    if tag == "circle":
        r = _num(el.get("r"))
        return _ellipse(_num(el.get("cx")), _num(el.get("cy")), r, r)
    if tag == "ellipse":
        return _ellipse(_num(el.get("cx")), _num(el.get("cy")), _num(el.get("rx")), _num(el.get("ry")))
    raise ValueError(f"unsupported svg element <{tag}>")


_NUMBER = r"[-+]?(?:\d*\.\d+|\d+\.?)(?:[eE][-+]?\d+)?"
_LEADING_RELATIVE_MOVE = re.compile(rf"^m\s*({_NUMBER})[\s,]*({_NUMBER})(.*)$", re.DOTALL)


def _absolute_start(path: str) -> str:
    """A path that starts with a relative `m` is measured from the origin, but
    once joined after another path it would be measured from that path's end.
    The pair after `m` is absolute; any pairs after it stay relative."""
    match = _LEADING_RELATIVE_MOVE.match(path)
    if not match:
        return path
    x, y, rest = match.groups()
    return f"M{x} {y}" + (f"l{rest}" if rest.strip() else "")


def svg_path(svg_text: str) -> str:
    root = ET.fromstring(svg_text)
    return " ".join(_absolute_start(element_path(child)) for child in root)


def fetch(name: str) -> str:
    url = _SVG_URL.format(version=LUCIDE_VERSION, name=name)
    with urllib.request.urlopen(url, timeout=20) as response:
        return response.read().decode("utf-8")


def main() -> None:
    lines = [_HEADER.format(version=LUCIDE_VERSION), "export const paths = {"]
    for name in sorted(ICONS):
        lines.append(f'    "{name}": "{svg_path(fetch(name))}",')
    lines.append("}")
    with open(_OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines) + "\n")
    print(f"wrote {len(ICONS)} icons to {os.path.normpath(_OUT)}")


if __name__ == "__main__":
    main()
